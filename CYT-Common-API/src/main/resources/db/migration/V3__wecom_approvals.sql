-- Business aliases and callback inbox are isolated by environment, system and mock/live mode.
CREATE TABLE gateway_wecom_form (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  env VARCHAR(32) NOT NULL,
  runtime VARCHAR(8) NOT NULL,
  system VARCHAR(32) NOT NULL,
  alias VARCHAR(64) NOT NULL,
  template_id VARCHAR(160) NOT NULL,
  field_aliases TEXT NOT NULL,
  description VARCHAR(255) NOT NULL DEFAULT '',
  updated_at TIMESTAMP(6) WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
  CONSTRAINT uq_wecom_form UNIQUE (env,runtime,system,alias)
);

CREATE TABLE gateway_wecom_submission (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  env VARCHAR(32) NOT NULL,
  runtime VARCHAR(8) NOT NULL,
  system VARCHAR(32) NOT NULL,
  profile VARCHAR(64) NOT NULL,
  approval_no VARCHAR(64) NOT NULL,
  template_id VARCHAR(160) NOT NULL,
  request_id VARCHAR(128) NOT NULL,
  created_at TIMESTAMP(6) WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
  CONSTRAINT uq_wecom_submission UNIQUE (env,runtime,system,request_id)
);
CREATE INDEX ix_wecom_submission_number ON gateway_wecom_submission (env,runtime,profile,approval_no);

CREATE TABLE gateway_wecom_event (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  env VARCHAR(32) NOT NULL,
  system VARCHAR(32) NOT NULL,
  event_id VARCHAR(64) NOT NULL,
  approval_no VARCHAR(64) NOT NULL DEFAULT '',
  payload_ciphertext TEXT NOT NULL,
  delivery_state VARCHAR(16) NOT NULL DEFAULT 'pending',
  attempts INT NOT NULL DEFAULT 0,
  next_attempt_at TIMESTAMP(6) WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
  last_error VARCHAR(64) NOT NULL DEFAULT '',
  created_at TIMESTAMP(6) WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
  CONSTRAINT uq_wecom_event UNIQUE (env,system,event_id)
);
CREATE INDEX ix_wecom_event_poll ON gateway_wecom_event (env,system,id);
CREATE INDEX ix_wecom_event_delivery ON gateway_wecom_event (delivery_state,next_attempt_at);
