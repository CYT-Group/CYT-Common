CREATE TABLE gateway_discord_session (
  env VARCHAR(32) NOT NULL,
  bot_id VARCHAR(32) NOT NULL,
  session_id VARCHAR(160) NOT NULL DEFAULT '',
  sequence_no BIGINT NULL,
  resume_url VARCHAR(512) NOT NULL DEFAULT '',
  lease_owner VARCHAR(64) NOT NULL DEFAULT '',
  lease_until TIMESTAMP(6) WITH TIME ZONE NULL,
  updated_at TIMESTAMP(6) WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
  PRIMARY KEY (env, bot_id)
);

CREATE TABLE gateway_discord_event (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  env VARCHAR(32) NOT NULL,
  bot_id VARCHAR(32) NOT NULL,
  event_key VARCHAR(64) NOT NULL,
  event_type VARCHAR(40) NOT NULL,
  payload TEXT NOT NULL,
  received_at TIMESTAMP(6) WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
  CONSTRAINT uq_discord_event UNIQUE (env, bot_id, event_key)
);
CREATE INDEX ix_discord_event_cursor ON gateway_discord_event (env, bot_id, id);
